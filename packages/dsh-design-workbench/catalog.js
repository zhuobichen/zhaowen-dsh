/** 「引用给 AI」的正文：由结构化字段拼出来，保证八个条目的措辞一致。 */
export function promptOf(style) {
  const lines = [
    `【设计样式】${style.name}（${style.id}）`,
    `一句话：${style.oneLine}`,
    `出处：${style.source}`,
    '',
    '颜色：',
    `  底 ${style.colors.bg}　面 ${style.colors.surface}　字 ${style.colors.text}　次 ${style.colors.muted}`,
    `  描边 ${style.colors.border}　强调 ${style.colors.accent}　语义 ok ${style.colors.ok} / warn ${style.colors.warn} / danger ${style.colors.danger}`,
    '',
    '形状与排版：',
    `  圆角 ${style.shape.radius}（小元素 ${style.shape.radiusSm}）`,
    `  投影 ${style.shape.shadow}`,
    `  字体 ${style.shape.font}；等宽 ${style.shape.mono}`,
    `  密度 上下内边距 ${style.shape.density}px`,
    '',
    '直接可用的 CSS：',
    ...style.tokens.map((t) => `  ${t}`),
    '',
    `视觉手法：${style.craft.join('；')}`,
    '',
    '约束：',
    ...SHARED_RULES.map((r) => `  - ${r}`),
    `  - 这个界面的定位是「${style.when}」，不要往「${style.avoid}」的方向加东西`,
  ]
  return lines.join('\n')
}

for (const s of STYLES) s.prompt = promptOf(s)

export const STYLE_IDS = STYLES.map((s) => s.id)

export function findStyle(id) {
  return STYLES.find((s) => s.id === id) || null
}

