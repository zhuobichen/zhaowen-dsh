const pairs = (text: string, dynasty: string): [string, string][] =>
  text
    .split(/\s+/)
    .map((name) => name.trim())
    .filter((name) => name !== '')
    .map((name) => [name, dynasty] as [string, string])

const MAP = new Map<string, string>([...pairs(TANG, '唐'), ...pairs(SONG, '宋'), ...Object.entries(EXTRA)])

/** 朝代表里没有的名字。 */
export const UNKNOWN_DYNASTY = '朝代不详'

/**
 * 作者的朝代；表里没有就返回 `null`（调用方自己决定显示什么）。
 * @param author - 作者名，如 `李白`。
 */
export const dynastyOf = (author: string | null | undefined): string | null => {
  if (author === null || author === undefined) return null

  const name = author.trim()

  if (name === '') return null
  if (name === '无名氏' || name === '不详') return null

  const hit = MAP.get(name)

  if (hit !== undefined) return hit

  // 太宗皇帝 / 高宗皇帝 这类：唐代帝王
  if (/^.+皇帝$/.test(name) && /^(太宗|高宗|中宗|睿宗|玄宗|肃宗|代宗|德宗|顺宗|宪宗|穆宗|敬宗|文宗|武宗|宣宗|懿宗|僖宗|昭宗|哀帝|则天)/.test(name)) {
    return '唐'
  }

  return null
}

/** 表里覆盖了多少个名字（给测试和文档用）。 */
export const dynastyTableSize = (): number => MAP.size
